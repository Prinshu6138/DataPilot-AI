import {test,expect} from '@playwright/test';
import {readFile} from 'node:fs/promises';
const csv=Buffer.from('Date,Region,Sales,Orders\n2026-01-01,West,10,2\n2026-01-02,East,20,4\n2026-02-01,West,,6\n2026-02-02,East,40,8\n2026-02-02,East,40,8\n');

test('dashboard, search, and responsive navigation',async({page})=>{
 const errors=[];page.on('pageerror',err=>errors.push(err.message));
 await page.goto('/');await expect(page.getByRole('heading',{name:/Welcome back, Alex/})).toBeVisible();
 await expect(page.getByRole('heading',{name:'Recent datasets'})).toBeVisible();
 await page.getByLabel('Activity period').selectOption('7');
 await page.keyboard.press('Control+k');
 await page.getByRole('textbox',{name:'Search workspace'}).fill('sales');
 await page.getByRole('button',{name:'Q4 Sales Performance.csv'}).last().click();
 await expect(page.getByRole('heading',{name:'Q4 Sales Performance.csv',exact:true})).toBeVisible();
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Open navigation'}).click();
 await page.getByRole('navigation').getByRole('button',{name:'Dashboard'}).click();
 await expect(page.getByRole('heading',{name:/Welcome back, Alex/})).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
 expect(errors).toEqual([]);
});

